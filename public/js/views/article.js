import { api, state, isOwner } from "../api.js";
import { esc, icon, fullDate, timeAgo, toast, sourceLabel } from "../ui.js";

// Renders the model's plain-text summary (lead sentence + "- " bullets) as safe HTML.
function summaryHTML(text) {
  const lines = text.split("\n").map((l) => l.trim()).filter(Boolean);
  let html = "";
  let inList = false;
  for (const line of lines) {
    const bullet = line.match(/^[-*•]\s+(.*)$/);
    if (bullet) {
      if (!inList) html += "<ul>";
      inList = true;
      html += `<li>${esc(bullet[1].replace(/\*\*(.+?)\*\*/g, "$1"))}</li>`;
    } else {
      if (inList) html += "</ul>";
      inList = false;
      html += `<p>${esc(line.replace(/\*\*(.+?)\*\*/g, "$1"))}</p>`;
    }
  }
  return inList ? `${html}</ul>` : html;
}

function aiCardHTML(slug, summary) {
  const head = (action = "") => `
    <div class="ai-head">
      <div class="ai-title"><span class="spark">${icon("sparkles")}</span> AI Summary</div>
      ${action}
    </div>`;

  if (!state.user) {
    const next = encodeURIComponent(`/article/${slug}`);
    return `
      <section class="ai-card" aria-label="AI summary">
        ${head(`<span class="badge">${icon("lock")} Members</span>`)}
        <div class="ai-locked">
          <p>Get the key points of this story in seconds. AI summaries are free with a Sprout account.</p>
          <div style="display:flex;gap:8px"><a class="btn btn-sm" href="/signin?next=${next}">Sign in</a><a class="btn btn-sm btn-primary" href="/signup?next=${next}">Create account</a></div>
        </div>
      </section>`;
  }
  if (summary) {
    return `
      <section class="ai-card" aria-label="AI summary">
        ${head(`<span class="badge badge-accent">Ready</span>`)}
        <div class="ai-body">${summaryHTML(summary)}</div>
        <div class="ai-foot">Generated by AI from this article. It may contain mistakes — read the full story for details.</div>
      </section>`;
  }
  return `
    <section class="ai-card" aria-label="AI summary">
      ${head(`<button class="btn btn-sm btn-primary" id="summarize" type="button">${icon("sparkles")} Summarize</button>`)}
      <div class="ai-body" id="ai-body"><p class="muted">Short on time? Get a quick AI summary of the key points before you read.</p></div>
    </section>`;
}

export async function articleView(main, { params, isCurrent }) {
  const slug = decodeURIComponent(params[0]);
  main.innerHTML = `
    <article class="container narrow article">
      <div class="skeleton sk-line" style="width:90px;margin-bottom:28px"></div>
      <div class="skeleton sk-line" style="width:120px"></div>
      <div class="skeleton" style="height:42px;margin:14px 0"></div>
      <div class="skeleton" style="height:42px;width:70%"></div>
      <div class="skeleton" style="height:140px;margin-top:30px;border-radius:14px"></div>
    </article>`;

  const { article: a, summary } = await api(`/articles/${encodeURIComponent(slug)}`);
  if (!isCurrent()) return;
  document.title = `${a.title} · Sprout`;

  const fromSource = a.source && a.source !== "original";
  main.innerHTML = `
    <article class="container narrow article fade-in">
      <a class="back" href="/">${icon("back")} All news</a>
      <header class="article-head">
        <div style="display:flex;gap:10px;align-items:center;flex-wrap:wrap">
          <a class="tag" href="/?category=${encodeURIComponent(a.category)}">${esc(a.category)}</a>
          ${a.status === "draft" ? `<span class="badge">Draft</span>` : ""}
        </div>
        <h1>${esc(a.title)}</h1>
        ${a.dek ? `<p class="dek">${esc(a.dek)}</p>` : ""}
        <div class="byline">
          <div class="meta">
            ${a.author ? `<span style="color:var(--text)">${esc(a.author)}</span><span class="dot"></span>` : ""}
            <span>${esc(sourceLabel(a))}</span><span class="dot"></span>
            <time datetime="${esc(a.publishedAt)}" title="${esc(fullDate(a.publishedAt))}">${esc(timeAgo(a.publishedAt))}</time><span class="dot"></span>
            <span>${a.readingMinutes} min read</span>
          </div>
          <div class="share-row">
            ${isOwner() ? `<a class="icon-btn" href="/studio/edit/${a.id}" title="Edit" aria-label="Edit article">${icon("pen")}</a>` : ""}
            <button class="icon-btn" id="share" type="button" title="Share" aria-label="Share">${icon("share")}</button>
          </div>
        </div>
      </header>
      <div id="ai-slot">${aiCardHTML(slug, summary)}</div>
      ${a.coverImage ? `<figure class="cover" style="margin-left:0;margin-right:0"><img src="${esc(a.coverImage)}" alt="" referrerpolicy="no-referrer" data-fallback /></figure>` : ""}
      <div class="prose">${a.html}</div>
      ${
        fromSource && a.sourceUrl
          ? `<aside class="source-note"><span class="muted">Originally published by <strong style="color:var(--text)">${esc(a.sourceName)}</strong></span><a class="btn btn-sm" href="${esc(a.sourceUrl)}" target="_blank" rel="noopener noreferrer">Read on ${esc(a.sourceName)} ${icon("external")}</a></aside>`
          : ""
      }
    </article>`;

  main.querySelector("#share").addEventListener("click", async () => {
    const url = location.href;
    if (navigator.share) {
      navigator.share({ title: a.title, url }).catch(() => {});
    } else {
      await navigator.clipboard?.writeText(url).catch(() => {});
      toast("Link copied to clipboard");
    }
  });

  const btn = main.querySelector("#summarize");
  btn?.addEventListener("click", async () => {
    const body = main.querySelector("#ai-body");
    btn.disabled = true;
    btn.innerHTML = `<span class="spinner"></span> Summarizing`;
    body.innerHTML = '<div class="skeleton sk-line"></div><div class="skeleton sk-line"></div><div class="skeleton sk-line"></div><div class="skeleton sk-line"></div>';
    try {
      const { summary: text } = await api(`/articles/${encodeURIComponent(slug)}/summary`, { method: "POST" });
      if (!isCurrent()) return;
      main.querySelector("#ai-slot").innerHTML = aiCardHTML(slug, text);
    } catch (err) {
      if (!isCurrent()) return;
      body.innerHTML = `<p class="form-error">${esc(err.message)}</p>`;
      btn.disabled = false;
      btn.innerHTML = `${icon("refresh")} Try again`;
    }
  });
}
